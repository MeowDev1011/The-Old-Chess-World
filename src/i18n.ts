const SUPPORTED_CODES = new Set<string>(SUPPORTED_LANGUAGES.map((l) => l.code));

export function detectInitialLanguage(): { lang: SupportedLang; isDeviceSupported: boolean } {
  if (typeof window === 'undefined' || !navigator) {
    return { lang: 'en', isDeviceSupported: true };
  }
  const rawLang = (navigator.language || (navigator.languages && navigator.languages[0]) || 'en').toLowerCase();
  const code = rawLang.split('-')[0] as SupportedLang;
  if (SUPPORTED_CODES.has(code)) {
    return { lang: code, isDeviceSupported: true };
  }
  return { lang: 'en', isDeviceSupported: false };
}

